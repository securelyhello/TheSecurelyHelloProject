#!/usr/bin/env python3
"""Generates every app and website icon from the brand SVGs.

  pip install cairosvg pillow
  tools/make_icons.py

Sources (docs/BRAND.md):
  assets/brand/logo.svg   the app icon: the Sealed note (cream bubble, ink
                          envelope flap, pear seal) on an ink tile
  assets/brand/mark.svg   the mark alone: one ink even-odd silhouette

Writes the Android adaptive / monochrome / notification icons and legacy
PNGs, iOS and macOS app icons, the Windows .ico, the web (PWA) icons, the
website favicon and social preview, and assets/brand PNGs used in the app.
"""
import io
import json
import math
import os
import re

import cairosvg
from PIL import Image, ImageDraw, ImageFont

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
BRAND = os.path.join(ROOT, 'assets', 'brand')
LOGO = os.path.join(BRAND, 'logo.svg')
MARK = os.path.join(BRAND, 'mark.svg')
RES = os.path.join(ROOT, 'android', 'app', 'src', 'main', 'res')

INK, PAPER, PEAR = '#12161C', '#F7F5EC', '#F7D21A'
NIGHT = '#0B1015'

# Sealed note geometry (512 viewBox), mirrored in assets/brand/logo.svg.
# The flap is a 24 px round-capped polyline and the seal a circle with an
# 8 px ink stroke; Android vectors get them as plain outlines (no strokes).
FLAP = ((150, 160), (256, 236), (362, 160))
FLAP_W = 12            # half of the stroke width
SEAL_C, SEAL_R, SEAL_RING = (256, 236), 26, 34   # pear disc, ink disc


def svg_png(path, size, *, square=False):
    """Renders [path] at [size] px. [square]: the ink tile fills the whole
    square (iOS masks the corners itself)."""
    svg = open(path, encoding='utf-8').read()
    if square:
        svg = svg.replace('rx="116"', 'rx="0"')
    png = cairosvg.svg2png(bytestring=svg.encode(), output_width=size, output_height=size)
    return Image.open(io.BytesIO(png)).convert('RGBA')


def silhouette_path():
    """The mark's one even-odd path (bubble, flap band and seal ring cut
    out, seal disc solid), from assets/brand/mark.svg."""
    svg = open(MARK, encoding='utf-8').read()
    return re.search(r'\bd="([^"]+)"', svg).group(1)


def bubble_path():
    """The cream speech-bubble path, from assets/brand/logo.svg."""
    svg = open(LOGO, encoding='utf-8').read()
    return re.search(r'<path[^>]*\bd="([^"]+)"', svg).group(1)


def _n(v):
    return ('%.2f' % v).rstrip('0').rstrip('.')


def flap_outline():
    """The flap stroke converted to an outline: a filled path with round
    caps, for Android vectors."""
    (ax, ay), (bx, by), (cx, cy) = FLAP
    w = FLAP_W
    length = math.hypot(bx - ax, by - ay)
    dx, dy = (bx - ax) / length, (by - ay) / length   # first leg direction
    nx, ny = dy, -dx                                  # upper normal, first leg
    mx, my = -nx, ny                                  # upper normal, second leg
    miter = w / abs(ny)

    def p(x, y):
        return f'{_n(x)} {_n(y)}'
    return (f'M{p(ax + w * nx, ay + w * ny)}L{p(bx, by - miter)}'
            f'L{p(cx + w * mx, cy + w * my)}A{w} {w} 0 0 1 {p(cx - w * mx, cy - w * my)}'
            f'L{p(bx - w * mx, by - w * my)}A{w} {w} 0 0 1 {p(bx - w * nx, by - w * ny)}'
            f'L{p(ax - w * nx, ay - w * ny)}A{w} {w} 0 0 1 {p(ax + w * nx, ay + w * ny)}Z')


def disc(cx, cy, r):
    return f'M{cx - r} {cy}a{r} {r} 0 1 0 {2 * r} 0a{r} {r} 0 1 0 {-2 * r} 0Z'


def write(path, data):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, 'w', encoding='utf-8') as f:
        f.write(data)


def android():
    # Adaptive icon: 108 dp viewport, the mark centred (its bounds are about
    # 104..408 by 112..402 of 512) inside the 66 dp safe circle.
    scale = 0.155
    tx, ty = 54 - 256 * scale, 54 - 257 * scale
    head = ('<?xml version="1.0" encoding="utf-8"?>\n'
            '<!-- Generated by tools/make_icons.py from assets/brand. -->\n'
            '<vector xmlns:android="http://schemas.android.com/apk/res/android"\n'
            '    android:width="108dp" android:height="108dp"\n'
            '    android:viewportWidth="108" android:viewportHeight="108">\n')
    group = (f'    <group android:scaleX="{scale}" android:scaleY="{scale}"\n'
             f'        android:translateX="{tx:.2f}" android:translateY="{ty:.2f}">\n')

    def path(fill, data, even_odd=False):
        rule = ' android:fillType="evenOdd"' if even_odd else ''
        return (f'        <path android:fillColor="{fill}"{rule}\n'
                f'            android:pathData="{data}" />\n')
    sx, sy = SEAL_C
    colour = (group + path(PAPER, bubble_path()) + path(INK, flap_outline())
              + path(INK, disc(sx, sy, SEAL_RING)) + path(PEAR, disc(sx, sy, SEAL_R))
              + '    </group>\n')
    mono = group + path('#FFFFFF', silhouette_path(), True) + '    </group>\n'
    write(os.path.join(RES, 'drawable', 'ic_launcher_foreground.xml'), head + colour + '</vector>\n')
    write(os.path.join(RES, 'drawable', 'ic_launcher_monochrome.xml'), head + mono + '</vector>\n')
    write(os.path.join(RES, 'values', 'ic_launcher_background.xml'),
          '<?xml version="1.0" encoding="utf-8"?>\n<resources>\n'
          f'    <color name="ic_launcher_background">{INK}</color>\n</resources>\n')
    write(os.path.join(RES, 'mipmap-anydpi-v26', 'ic_launcher.xml'),
          '<?xml version="1.0" encoding="utf-8"?>\n'
          '<!-- Adaptive launcher icon (Android 8+); older versions use the PNGs in\n'
          '     mipmap-*dpi. All generated by tools/make_icons.py. -->\n'
          '<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">\n'
          '    <background android:drawable="@color/ic_launcher_background" />\n'
          '    <foreground android:drawable="@drawable/ic_launcher_foreground" />\n'
          '    <monochrome android:drawable="@drawable/ic_launcher_monochrome" />\n'
          '</adaptive-icon>\n')
    # Notification icon: the white silhouette only (Android tints it),
    # viewport cropped to the mark (96..416).
    write(os.path.join(RES, 'drawable', 'ic_stat_notify.xml'),
          '<?xml version="1.0" encoding="utf-8"?>\n'
          '<!-- Notification icon, white only (generated by tools/make_icons.py). -->\n'
          '<vector xmlns:android="http://schemas.android.com/apk/res/android"\n'
          '    android:width="24dp" android:height="24dp"\n'
          '    android:viewportWidth="320" android:viewportHeight="320">\n'
          '    <group android:translateX="-96" android:translateY="-96">\n'
          '        <path android:fillColor="#FFFFFF" android:fillType="evenOdd"\n'
          f'            android:pathData="{silhouette_path()}" />\n'
          '    </group>\n'
          '</vector>\n')
    # The old gradient background is gone; remove its generated drawable.
    old = os.path.join(RES, 'drawable', 'ic_launcher_background_gradient.xml')
    if os.path.exists(old):
        os.remove(old)
    # Launch window: paper in light, night in dark (styles.xml points at the
    # launch_background drawable, which uses this colour).
    write(os.path.join(RES, 'values', 'launch_colors.xml'),
          '<?xml version="1.0" encoding="utf-8"?>\n<resources>\n'
          f'    <color name="launch_background">{PAPER}</color>\n</resources>\n')
    write(os.path.join(RES, 'values-night', 'launch_colors.xml'),
          '<?xml version="1.0" encoding="utf-8"?>\n<resources>\n'
          f'    <color name="launch_background">{NIGHT}</color>\n</resources>\n')
    for d in ('drawable', 'drawable-v21'):
        write(os.path.join(RES, d, 'launch_background.xml'),
              '<?xml version="1.0" encoding="utf-8"?>\n'
              '<!-- Launch window: paper (light) / night (dark), see values*/launch_colors.xml. -->\n'
              '<layer-list xmlns:android="http://schemas.android.com/apk/res/android">\n'
              '    <item android:drawable="@color/launch_background" />\n'
              '</layer-list>\n')
    for dpi, size in {'mdpi': 48, 'hdpi': 72, 'xhdpi': 96, 'xxhdpi': 144, 'xxxhdpi': 192}.items():
        svg_png(LOGO, size).save(os.path.join(RES, f'mipmap-{dpi}', 'ic_launcher.png'))


def apple():
    ios = os.path.join(ROOT, 'ios', 'Runner', 'Assets.xcassets', 'AppIcon.appiconset')
    for f in os.listdir(ios):
        if f.endswith('.png'):
            size = Image.open(os.path.join(ios, f)).size[0]
            # No transparency on iOS: the full-bleed ink square.
            svg_png(LOGO, size, square=True).convert('RGB').save(os.path.join(ios, f))
    mac = os.path.join(ROOT, 'macos', 'Runner', 'Assets.xcassets', 'AppIcon.appiconset')
    for f in os.listdir(mac):
        if f.endswith('.png'):
            size = Image.open(os.path.join(mac, f)).size[0]
            # macOS icons carry their own rounded shape, with a margin.
            canvas = Image.new('RGBA', (size, size), (0, 0, 0, 0))
            inner = round(size * 0.82)
            canvas.alpha_composite(svg_png(LOGO, inner), ((size - inner) // 2, (size - inner) // 2))
            canvas.save(os.path.join(mac, f))


def windows():
    big = svg_png(LOGO, 256)
    big.save(os.path.join(ROOT, 'windows', 'runner', 'resources', 'app_icon.ico'),
             sizes=[(16, 16), (24, 24), (32, 32), (48, 48), (64, 64), (128, 128), (256, 256)])


def web():
    w = os.path.join(ROOT, 'web')
    svg_png(LOGO, 32).save(os.path.join(w, 'favicon.png'))
    for name, size in {'Icon-192.png': 192, 'Icon-512.png': 512}.items():
        svg_png(LOGO, size).save(os.path.join(w, 'icons', name))
    for name, size in {'Icon-maskable-192.png': 192, 'Icon-maskable-512.png': 512}.items():
        svg_png(LOGO, size, square=True).save(os.path.join(w, 'icons', name))
    manifest = os.path.join(w, 'manifest.json')
    if os.path.exists(manifest):
        m = json.load(open(manifest, encoding='utf-8'))
        m['background_color'] = PAPER
        m['theme_color'] = INK
        json.dump(m, open(manifest, 'w', encoding='utf-8'), indent=4)


def website():
    site = os.path.join(ROOT, 'website', 'assets')
    with open(os.path.join(site, 'logo.svg'), 'w', encoding='utf-8') as f:
        f.write(open(LOGO, encoding='utf-8').read())
    svg_png(LOGO, 32).save(os.path.join(site, 'favicon-32.png'))
    svg_png(LOGO, 180).save(os.path.join(site, 'apple-touch-icon.png'))
    # Social preview (1200x630): paper, the icon and the name in Chillax.
    og = Image.new('RGB', (1200, 630), PAPER)
    icon = svg_png(LOGO, 260)
    og.paste(icon, (120, 185), icon)
    font_dir = os.path.join(ROOT, 'assets', 'fonts')
    title = ImageFont.truetype(os.path.join(font_dir, 'Chillax-Semibold.ttf'), 84)
    sub = ImageFont.truetype(os.path.join(font_dir, 'Inter-Medium.ttf'), 34)
    d = ImageDraw.Draw(og)
    d.text((430, 215), 'Securely Hello', font=title, fill=INK)
    d.text((432, 340), 'Say hello. Keep it between you.', font=sub, fill='#3C424A')
    d.text((432, 388), 'End-to-end encrypted. Made in India.', font=sub, fill='#565B63')
    d.rectangle((0, 610, 1200, 630), fill=PEAR)
    og.save(os.path.join(site, 'og.png'), optimize=True)


def in_app():
    for size in (96, 192, 384):
        svg_png(LOGO, size).save(os.path.join(BRAND, f'logo-{size}.png'))


if __name__ == '__main__':
    android()
    apple()
    windows()
    web()
    website()
    in_app()
    print('icons written')
